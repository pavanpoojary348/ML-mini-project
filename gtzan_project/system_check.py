# system_check.py
"""Simple verification script for GTZAN genre classification project.

This script checks that:
1. Model checkpoints can be loaded without errors.
2. The dataset loader works and returns valid spectrogram tensors.
3. Inference runs on a few test samples yielding predictions.

Run with:
    python system_check.py

It will print a concise report indicating success/failure for each step.
"""

import os
import torch
from torch.utils.data import DataLoader

# Project imports (adjust if module path differs)
import sys, os
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))
from gtzan_project.models import EnhancedSECNN, MobileNetV2Classifier
from gtzan_project.dataset import GTZAN3SecMelDataset, build_3s_dataloaders

def load_model(model_cls, checkpoint_path, device):
    """Instantiate a model class and load weights from a checkpoint.
    Returns the model in eval mode.
    """
    model = model_cls().to(device)
    state = torch.load(checkpoint_path, map_location=device)
    # Some checkpoints may be stored as {'model_state_dict': ...}
    if isinstance(state, dict) and 'model_state_dict' in state:
        model.load_state_dict(state['model_state_dict'])
    else:
        model.load_state_dict(state)
    model.eval()
    return model

def main():
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f"Using device: {device}")

    # Paths to checkpoints (relative to project root)
    checkpoints_dir = os.path.join(os.path.dirname(__file__), '..', 'results_gtzan_high_acc')
    secnn_ckpt = os.path.join(checkpoints_dir, 'best_secnn_3s.pt')
    mobilenet_ckpt = os.path.join(checkpoints_dir, 'best_mobilenet_3s.pt')

    # Verify checkpoint existence
    for ckpt in [secnn_ckpt, mobilenet_ckpt]:
        if not os.path.isfile(ckpt):
            raise FileNotFoundError(f"Checkpoint not found: {ckpt}")
    print("[OK] Checkpoints found.")

    # Load models
    secnn = load_model(EnhancedSECNN, secnn_ckpt, device)
    mobilenet = load_model(MobileNetV2Classifier, mobilenet_ckpt, device)
    print("[OK] Models loaded successfully.")

    # Load a few test samples
    # Path to the mel spectrogram cache (generated by preprocess_3s_mels.py)
    npz_path = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', 'data', 'gtzan', 'mel_spectrograms_3s.npz'))
    # Load train/val/test loaders (we only need the test loader here)
    _, _, test_loader = build_3s_dataloaders(npz_path, batch_size=5)
    test_iter = iter(test_loader)
    sample_batch = next(test_iter)
    inputs, labels, _ = sample_batch
    inputs = inputs.to(device)
    print(f"[OK] Loaded {inputs.shape[0]} test samples.")

    # Run inference
    with torch.no_grad():
        secnn_logits = secnn(inputs)
        mobilenet_logits = mobilenet(inputs)
    # Convert to probabilities
    secnn_probs = torch.nn.functional.softmax(secnn_logits, dim=1)
    mobilenet_probs = torch.nn.functional.softmax(mobilenet_logits, dim=1)

    # Simple sanity checks
    assert secnn_probs.shape == (inputs.shape[0], 10), "Unexpected SE-CNN output shape"
    assert mobilenet_probs.shape == (inputs.shape[0], 10), "Unexpected MobileNet output shape"
    print("[OK] Inference shapes are correct.")

    # Print predictions for the first few samples
    class_names = [
        "blues", "classical", "country", "disco", "hiphop",
        "jazz", "metal", "pop", "reggae", "rock"
    ]
    for i in range(inputs.shape[0]):
        secnn_pred = class_names[secnn_probs[i].argmax().item()]
        mobilenet_pred = class_names[mobilenet_probs[i].argmax().item()]
        true_label = class_names[labels[i].item()]
        print(f"Sample {i+1}: true={true_label} | SE-CNN={secnn_pred} ({secnn_probs[i].max():.2f}) | MobileNet={mobilenet_pred} ({mobilenet_probs[i].max():.2f})")

    print("\nSystem check completed successfully!")

if __name__ == "__main__":
    main()
